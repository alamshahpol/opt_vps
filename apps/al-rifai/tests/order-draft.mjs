// Admin draft composition regressions. The draft must never look confirmed and
// must expose missing fields and provenance.
import test from 'node:test';
import assert from 'node:assert/strict';
import {composeAdminDraft, draftGaps, draftWarnings, draftProvenance} from '../lib/order-draft.ts';

const order = {
  motherVessel: 'MV. Alpha Unity', lighterVessel: 'MV. Light One',
  masterMobile: '01829-984145', bookingDate: '03/10/26',
  destination: 'O/A To Local', sourceMessageId: 'wamid-123', sourceTime: '2026-10-03T13:24:13Z',
  clientName: 'Hridoy', clientPhone: '8801670535255',
};

test('draft preserves the client order and leaves admin assignment blank', () => {
  const text = composeAdminDraft(order);
  assert.match(text, /Mother Vessel: MV\. Alpha Unity/);
  assert.match(text, /Lighter Vessel: MV\. Light One/);
  assert.match(text, /Master Mobile: 01829-984145/);
  assert.match(text, /Escort Name: $/m);
  assert.match(text, /Escort Mobile: $/m);
  assert.match(text, /Shift: $/m);
  assert.match(text, /Source reference: wamid-123/);
  assert.match(text, /Draft — pending authorized Admin assignment\./);
  // A draft must never assert confirmation.
  assert.doesNotMatch(text, /confirmed|confirmed program/i);
});

test('missing client fields and pending assignment fields are explained', () => {
  const gaps = draftGaps({...order, masterMobile: ''});
  assert.ok(gaps.some((gap) => gap.field === 'masterMobile' && gap.required));
  assert.ok(gaps.some((gap) => gap.field === 'escortName' && !gap.required));
  const warnings = draftWarnings({...order, masterMobile: ''});
  assert.ok(warnings.some((warning) => /Master mobile missing/.test(warning)));
  assert.ok(warnings.some((warning) => /intentionally blank/.test(warning)));
});

test('provenance keeps client, phone, message id and source time', () => {
  const provenance = draftProvenance(order);
  assert.match(provenance, /Hridoy/);
  assert.match(provenance, /8801670535255/);
  assert.match(provenance, /wamid-123/);
  assert.match(provenance, /2026-10-03 13:24/);
});

test('missing source reference is surfaced, not invented', () => {
  const warnings = draftWarnings({...order, sourceMessageId: null});
  assert.ok(warnings.some((warning) => /Source message reference is unavailable/.test(warning)));
  assert.match(composeAdminDraft({...order, sourceMessageId: null}), /Source reference: —/);
});

test('EXACT and VARIANT confirmation text is not generated by drafts', () => {
  const text = composeAdminDraft({...order, escortName: 'Md. Osman', escortMobile: '01754334400', dutyDate: '2026-10-03', shift: 'N'});
  assert.match(text, /Escort Name: Md\. Osman/);
  assert.doesNotMatch(text, /confirmed/i);
});
